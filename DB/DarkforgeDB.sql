PRAGMA foreign_keys = ON;

BEGIN;

-- Models

CREATE TABLE PLT(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
EntityData BLOB NOT NULL
);

CREATE TABLE PGA(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
EntityData BLOB NOT NULL
);

CREATE TABLE RPF(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
PGAID INTEGER REFERENCES PGA(EntityID),
PLTID INTEGER REFERENCES PLT(EntityID),
Width INTEGER NOT NULL,
Height INTEGER NOT NULL,
CLUT INTEGER NOT NULL,
TexRow INTEGER NOT NULL,
TexX INTEGER NOT NULL,
TexY INTEGER NOT NULL,
CLUTRow INTEGER NOT NULL,
CLUTX INTEGER NOT NULL,
CLUTY INTEGER NOT NULL
);

CREATE TABLE WL(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
EntityData BLOB NOT NULL,
SampleRate INTEGER NOT NULL,
BlockCountPerChannel INTEGER NOT NULL,
ChannelCount INTEGER NOT NULL,
ThresholdBits INTEGER NOT NULL
);

CREATE TABLE FKR(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
TargetFPS INTEGER
);

CREATE TABLE BN(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
FKRID INTEGER REFERENCES FKR(EntityID),
Parent INTEGER REFERENCES BN(EntityID),
EntityData BLOB NOT NULL
);

CREATE TABLE ANM(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
FKRID INTEGER REFERENCES FKR(EntityID)
);

CREATE TABLE TK(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
ANMID INTEGER REFERENCES ANM(EntityID),
BNID INTEGER REFERENCES BN(EntityID),
T_Count INTEGER,
R_Count INTEGER,
S_Count INTEGER,
EntityData BLOB NOT NULL
);

CREATE TABLE MDL(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
TargetTextureWidth INTEGER NOT NULL,
TargetTextureHeight INTEGER NOT NULL,
TargetTextureOffsetX INTEGER NOT NULL,
TargetTextureOffsetY INTEGER NOT NULL
);

CREATE TABLE VT(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
EntityData BLOB NOT NULL
);

CREATE TABLE IND(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
EntityData BLOB NOT NULL
);

CREATE TABLE UV(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
EntityData BLOB NOT NULL
);

CREATE TABLE NRM(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
EntityData BLOB NOT NULL
);

CREATE TABLE MSH(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
MDLID INTEGER REFERENCES MDL(EntityID),
VTID INTEGER REFERENCES VT(EntityID),
INDID INTEGER REFERENCES IND(EntityID),
UVID INTEGER REFERENCES UV(EntityID),
NRMID INTEGER REFERENCES NRM(EntityID),
BNID INTEGER REFERENCES BN(EntityID),
Material INTEGER NOT NULL
);

CREATE TABLE AST(
EntityID INTEGER PRIMARY KEY AUTOINCREMENT,
MDLID INTEGER REFERENCES MDL(EntityID),
FKRID INTEGER REFERENCES FKR(EntityID),
PrecisionBits INTEGER NOT NULL
);

-- Files

CREATE TABLE BMP(
EntityID TEXT PRIMARY KEY,
EntityData BLOB NOT NULL
);

CREATE TABLE WAV(
EntityID TEXT PRIMARY KEY,
EntityData BLOB NOT NULL
);

CREATE TABLE GLB(
EntityID TEXT PRIMARY KEY,
EntityData BLOB NOT NULL
);

-- Active

CREATE TABLE ActiveRPF(
ID INTEGER PRIMARY KEY REFERENCES RPF(EntityID),
FileID TEXT NOT NULL REFERENCES BMP(EntityID),
CLUTSize INTEGER NOT NULL,
RAlpha INTEGER,
GAlpha INTEGER,
BAlpha INTEGER,
AlphaPresent INTEGER NOT NULL,
CompressionMode INTEGER NOT NULL
);

CREATE TABLE ActiveWL(
ID INTEGER PRIMARY KEY REFERENCES WL(EntityID),
FileID TEXT NOT NULL REFERENCES WAV(EntityID),
Looping INTEGER NOT NULL,
Channels INTEGER NOT NULL,
Threshold INTEGER NOT NULL
);

CREATE TABLE ActiveAST(
ID INTEGER PRIMARY KEY REFERENCES AST(EntityID),
FileID TEXT NOT NULL REFERENCES GLB(EntityID),
PrecisionBits INTEGER NOT NULL,
FPS INTEGER
);

CREATE TRIGGER trg_Delete_RPF_Before BEFORE DELETE ON RPF
BEGIN
    DELETE FROM ActiveRPF WHERE ID = OLD.EntityID;
END;

CREATE TRIGGER trg_Delete_RPF_After AFTER DELETE ON RPF
BEGIN
    DELETE FROM PGA WHERE EntityID = OLD.PGAID;
    DELETE FROM PLT WHERE EntityID = OLD.PLTID;
END;

CREATE TRIGGER trg_Delete_WL_Before BEFORE DELETE ON WL
BEGIN
    DELETE FROM ActiveWL WHERE ID = OLD.EntityID;
END;

CREATE TRIGGER trg_Delete_AST_Before BEFORE DELETE ON AST
BEGIN
    DELETE FROM ActiveAST WHERE ID = OLD.EntityID;
END;

CREATE TRIGGER trg_Delete_AST_After AFTER DELETE ON AST
BEGIN
    DELETE FROM MDL WHERE EntityID = OLD.MDLID;
    DELETE FROM FKR WHERE EntityID = OLD.FKRID;
END;

CREATE TRIGGER trg_Delete_MDL_Before BEFORE DELETE ON MDL
BEGIN
    DELETE FROM MSH WHERE MDLID = OLD.EntityID;
END;

CREATE TRIGGER trg_Delete_MSH_After AFTER DELETE ON MSH
BEGIN
    DELETE FROM VT WHERE EntityID = OLD.VTID;
    DELETE FROM IND WHERE EntityID = OLD.INDID;
    DELETE FROM UV WHERE EntityID = OLD.UVID;
    DELETE FROM NRM WHERE EntityID = OLD.NRMID;
END;

CREATE TRIGGER trg_Delete_FKR_Before BEFORE DELETE ON FKR
BEGIN
    DELETE FROM ANM WHERE FKRID = OLD.EntityID;
    DELETE FROM BN WHERE FKRID = OLD.EntityID;
END;

CREATE TRIGGER trg_Delete_ANM_Before BEFORE DELETE ON ANM
BEGIN
    DELETE FROM TK WHERE ANMID = OLD.EntityID;
END;

COMMIT;